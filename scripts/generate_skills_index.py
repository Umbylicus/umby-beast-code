#!/usr/bin/env python3
"""Generate SKILLS-INDEX.md from skill and subagent frontmatter.

Writes:
  SKILLS-INDEX.md                         (repo root, committed)
  skills/beast-code/SKILLS-INDEX.md       (installed with the orchestrator)

Usage:
  python3 scripts/generate_skills_index.py
  python3 scripts/generate_skills_index.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = ROOT / "skills"
AGENTS_DIR = ROOT / "agents"
ROOT_INDEX = ROOT / "SKILLS-INDEX.md"
INSTALLED_INDEX = ROOT / "skills" / "beast-code" / "SKILLS-INDEX.md"

# Major = drives a whole build or mode. Helpers are invoked by majors.
MAJOR_SKILLS = (
    "beast-code",
    "critic-mode",
    "game-mode",
    "sick-social",
    "arena",
)

HEADER = """# Skills Index

<!-- Generated by scripts/generate_skills_index.py. Do not edit by hand. -->

Catalog of every skill and subagent in this tree. Major skills (`beast-code`,
`critic-mode`, `game-mode`, `sick-social`, `arena`) read this file at the start
of every task and follow `beast-code/references/select-skills.md`.

After install this copy lives at `beast-code/SKILLS-INDEX.md` beside the other
skills. Sibling path from any skill: `../beast-code/SKILLS-INDEX.md`.
"""


def parse_frontmatter(text: str) -> dict[str, str]:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    raw = text[3:end].lstrip("\n")
    result: dict[str, str] = {}
    key: str | None = None
    buf: list[str] = []
    folded = False

    def flush() -> None:
        nonlocal key, buf, folded
        if key is None:
            return
        value = "\n".join(buf) if folded else " ".join(x.strip() for x in buf)
        result[key] = re.sub(r"\s+", " ", value).strip().strip('"').strip("'")
        key, buf, folded = None, [], False

    for line in raw.splitlines():
        if key and folded and (line.startswith("  ") or line.startswith("\t")):
            buf.append(line.strip())
            continue
        if key and folded and not line.strip():
            continue
        m = re.match(r"^([A-Za-z0-9_]+):\s*(.*)$", line)
        if m:
            flush()
            key = m.group(1)
            rest = m.group(2)
            if rest in (">", ">-", "|", "|-"):
                folded = True
                buf = []
            else:
                folded = False
                buf = [rest]
        elif key and line.startswith(" ") and ":" not in line.split("#")[0]:
            buf.append(line.strip())
    flush()
    return result


def yaml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def collect_skills() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for path in sorted(SKILLS_DIR.iterdir()):
        if not path.is_dir():
            continue
        skill_md = path / "SKILL.md"
        if not skill_md.exists():
            continue
        fm = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = fm.get("name") or path.name
        rows.append(
            {
                "name": name,
                "kind": "skill",
                "major": "true" if name in MAJOR_SKILLS else "false",
                "when_to_use": fm.get("description", "").strip(),
            }
        )
    return rows


def collect_agents() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for path in sorted(AGENTS_DIR.glob("*.md")):
        fm = parse_frontmatter(path.read_text(encoding="utf-8"))
        name = fm.get("name") or path.stem
        rows.append(
            {
                "name": name,
                "kind": "subagent",
                "major": "false",
                "when_to_use": fm.get("description", "").strip(),
            }
        )
    return rows


def render(skills: list[dict[str, str]], agents: list[dict[str, str]]) -> str:
    yaml_lines = ["```yaml", "generated_by: scripts/generate_skills_index.py"]
    yaml_lines.append("major_skills:")
    for name in MAJOR_SKILLS:
        yaml_lines.append(f"  - {name}")
    yaml_lines.append("skills:")
    for row in skills:
        yaml_lines.append(f"  - name: {row['name']}")
        yaml_lines.append(f"    kind: {row['kind']}")
        yaml_lines.append(f"    major: {row['major']}")
        yaml_lines.append(f'    when_to_use: "{yaml_escape(row["when_to_use"])}"')
    yaml_lines.append("subagents:")
    for row in agents:
        yaml_lines.append(f"  - name: {row['name']}")
        yaml_lines.append(f"    kind: {row['kind']}")
        yaml_lines.append(f'    when_to_use: "{yaml_escape(row["when_to_use"])}"')
    yaml_lines.append("```")

    def table(rows: list[dict[str, str]], with_major: bool) -> str:
        if with_major:
            lines = ["| name | major | when_to_use |", "| :--- | :--- | :--- |"]
            for row in rows:
                major = "yes" if row["major"] == "true" else "no"
                lines.append(f"| `{row['name']}` | {major} | {row['when_to_use']} |")
        else:
            lines = ["| name | when_to_use |", "| :--- | :--- |"]
            for row in rows:
                lines.append(f"| `{row['name']}` | {row['when_to_use']} |")
        return "\n".join(lines)

    parts = [
        HEADER.rstrip(),
        "",
        "## Machine-readable catalog",
        "",
        *yaml_lines,
        "",
        "## Skills",
        "",
        table(skills, with_major=True),
        "",
        "## Subagents",
        "",
        table(agents, with_major=False),
        "",
        f"Count: {len(skills)} skills, {len(agents)} subagents, {len(MAJOR_SKILLS)} major.",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate SKILLS-INDEX.md from this tree.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if committed indexes are stale.")
    args = parser.parse_args()

    skills = collect_skills()
    agents = collect_agents()
    if not skills:
        print("No skills found.", file=sys.stderr)
        return 1
    body = render(skills, agents)

    if args.check:
        failures: list[str] = []
        for path in (ROOT_INDEX, INSTALLED_INDEX):
            if not path.exists():
                failures.append(f"missing {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != body:
                failures.append(f"stale {path.relative_to(ROOT)}")
        if failures:
            print("SKILLS-INDEX.md is stale. Run: python3 scripts/generate_skills_index.py")
            for item in failures:
                print(f"  - {item}")
            return 1
        print(f"SKILLS-INDEX.md is current ({len(skills)} skills, {len(agents)} subagents).")
        return 0

    ROOT_INDEX.write_text(body, encoding="utf-8")
    INSTALLED_INDEX.parent.mkdir(parents=True, exist_ok=True)
    INSTALLED_INDEX.write_text(body, encoding="utf-8")
    print(f"Wrote {ROOT_INDEX.relative_to(ROOT)} and {INSTALLED_INDEX.relative_to(ROOT)}")
    print(f"  {len(skills)} skills, {len(agents)} subagents, majors: {', '.join(MAJOR_SKILLS)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
